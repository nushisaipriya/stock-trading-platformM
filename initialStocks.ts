import { StockData, PricePoint } from '../types/stock';

function generateHistoricalData(basePrice: number, points: number = 30, volatility: number = 0.015): PricePoint[] {
  const history: PricePoint[] = [];
  let currentPrice = basePrice * 0.92;
  const now = Date.now();
  const step = 60 * 1000; // 1 minute intervals

  for (let i = points; i >= 0; i--) {
    const timestamp = now - i * step;
    const date = new Date(timestamp);
    const timeStr = date.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });

    const changePercent = (Math.random() - 0.48) * volatility * 2;
    const open = currentPrice;
    currentPrice = Math.max(1, currentPrice * (1 + changePercent));
    const high = Math.max(open, currentPrice) * (1 + Math.random() * 0.005);
    const low = Math.min(open, currentPrice) * (1 - Math.random() * 0.005);
    const close = currentPrice;
    const volume = Math.floor(10000 + Math.random() * 50000);

    history.push({
      time: timeStr,
      timestamp,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });
  }

  return history;
}

